export function getSubjectsForExam(examType: string): string[] {
  return [...new Set(
    PRACTICE_QUESTIONS
      .filter(q => q.exam_type === examType)
      .map(q => q.subject),
  )].sort()
}

export function getYearsForSubject(examType: string, subject: string): number[] {
  return [...new Set(
    PRACTICE_QUESTIONS
      .filter(q => q.exam_type === examType && q.subject === subject)
      .map(q => q.year),
  )].sort((a, b) => b - a)
}

export function getQuestionsForQuiz(
  examType: string,
  subject: string,
  year: number,
  limit = 10,
): PracticeQuestion[] {
  const pool = PRACTICE_QUESTIONS.filter(
    q => q.exam_type === examType && q.subject === subject && q.year === year,
  )
  const shuffled = [...pool]
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }
  return shuffled.slice(0, limit)
}

